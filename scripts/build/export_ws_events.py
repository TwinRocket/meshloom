#!/usr/bin/env python3
"""Write (or check) frontend/src/wsEventTypes.ts from the WsEvent enumeration.

    uv run python scripts/build/export_ws_events.py          # regenerate
    uv run python scripts/build/export_ws_events.py --check  # fail when stale

The server's ``WsEvent`` (``app/auth/ws_events.py``) is the only list of
WebSocket event types; the frontend's ``WsEventType`` union and the type
check in ``frontend/src/wsEvents.ts`` come from this generated file.
``tests/test_ws_event_export.py`` runs ``--check``.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from app.auth.ws_events import WsEvent  # noqa: E402

OUT_PATH = ROOT / "frontend" / "src" / "wsEventTypes.ts"


def render() -> str:
    lines = [
        "// Generated by scripts/build/export_ws_events.py from app/auth/ws_events.py.",
        "// Do not edit: change WsEvent on the server and regenerate.",
        "",
        "/** Every WebSocket event type the server sends, with the permission needed to receive it. */",
        "export const WS_EVENT_PERMISSIONS = {",
        *(f"  {member.value}: '{member.permission}'," for member in WsEvent),
        "} as const;",
        "",
        "export type WsEventType = keyof typeof WS_EVENT_PERMISSIONS;",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    content = render()
    if "--check" in argv:
        if not OUT_PATH.exists() or OUT_PATH.read_text() != content:
            print(f"{OUT_PATH.relative_to(ROOT)} is stale: run {Path(__file__).relative_to(ROOT)}")
            return 1
        return 0
    OUT_PATH.write_text(content)
    print(f"Wrote {OUT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
