"""Mixed-script check for names shown as identities (UTS #39, "Highly Restrictive").

A word passes when its letters share one script, or fit one of the allowed
combinations Latin + Han + Hiragana + Katakana (Jpan), Latin + Han + Bopomofo (Hanb) or
Latin + Han + Hangul (Kore). Characters use Script_Extensions when they have it (U+30FC
is Hiragana and Katakana), and Common or Inherited characters never count as a script.
The Unicode tables are `app/data/unicode_scripts.json`, generated by
`scripts/data/refresh_unicode_scripts.py`, so the answer does not depend on the Python
version.

The restriction level is applied **per word**, not to the whole string as UTS #39
defines it: `Mesh Сеть` (a Latin word, then a Cyrillic word) passes, so a name may mix
languages (`Погода GPS-трекер`). What it refuses is a look-alike inside one word
(`Meѕhloom`). This is deliberate, not full UTS #39 conformance.
"""

import json
import unicodedata
from bisect import bisect_right
from functools import lru_cache
from pathlib import Path

_DATA = Path(__file__).resolve().parent.parent / "data" / "unicode_scripts.json"

# UTS #39 section 5.1 augmentation: the ideographic and kana/hangul scripts also stand
# for the combinations they are allowed in, and Latin is allowed in all of them.
_AUGMENT = {
    "Han": {"Hanb", "Jpan", "Kore"},
    "Hiragana": {"Jpan"},
    "Katakana": {"Jpan"},
    "Bopomofo": {"Hanb"},
    "Hangul": {"Kore"},
    "Latin": {"Hanb", "Jpan", "Kore"},
}


@lru_cache(maxsize=1)
def _tables() -> tuple[list[str], list[int], list[tuple[int, int, int]], list[int], list]:
    data = json.loads(_DATA.read_text(encoding="utf-8"))
    ranges = [tuple(r) for r in data["ranges"]]
    exts = data["extensions"]
    return (
        data["scripts"],
        [r[0] for r in ranges],
        ranges,
        [e[0] for e in exts],
        exts,
    )


def script_set(char: str) -> frozenset[str] | None:
    """Script_Extensions of a character, or None for Common/Inherited/unassigned."""
    names, starts, ranges, ext_starts, exts = _tables()
    cp = ord(char)
    i = bisect_right(ext_starts, cp) - 1
    if i >= 0 and exts[i][0] <= cp <= exts[i][1]:
        return frozenset(names[s] for s in exts[i][2])
    i = bisect_right(starts, cp) - 1
    if i >= 0 and ranges[i][0] <= cp <= ranges[i][1]:
        return frozenset({names[ranges[i][2]]})
    return None


def _augmented(scripts: frozenset[str]) -> set[str]:
    out = set(scripts)
    for s in scripts:
        out |= _AUGMENT.get(s, set())
    return out


def is_restricted_word(word: str) -> bool:
    """True when the word is single-script or an allowed combination."""
    common: set[str] | None = None
    for char in word:
        scripts = script_set(char)
        if scripts is None:
            continue
        aug = _augmented(scripts)
        common = aug if common is None else common & aug
        if not common:
            return False
    return True


def words(text: str) -> list[str]:
    """Maximal runs of letters and marks (a combining mark must not split a word)."""
    out: list[str] = []
    current: list[str] = []
    for char in unicodedata.normalize("NFKC", text):
        if unicodedata.category(char)[0] in ("L", "M"):
            current.append(char)
        elif current:
            out.append("".join(current))
            current = []
    if current:
        out.append("".join(current))
    return out


def mixed_script_word(text: str) -> bool:
    """True when one word of the text mixes scripts (per word, see the module docstring)."""
    return any(not is_restricted_word(w) for w in words(text))
